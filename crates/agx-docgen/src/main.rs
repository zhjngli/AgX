fn sanitize_markdown(markdown: &str) -> String {
    let markdown = strip_clap_markdown_title(markdown);
    strip_alias_annotations(&markdown)
}

fn strip_clap_markdown_title(markdown: &str) -> String {
    let Some(first_line_end) = markdown.find('\n') else {
        return markdown.to_owned();
    };

    let first_line = &markdown[..first_line_end];
    if first_line != CLAP_MARKDOWN_TITLE {
        return markdown.to_owned();
    }

    let mut remainder = &markdown[first_line_end + 1..];
    if remainder.starts_with('\n') {
        remainder = &remainder[1..];
    }

    remainder.to_owned()
}

fn strip_alias_annotations(markdown: &str) -> String {
    markdown
        .replace(" [alias: ", " (alias: ")
        .replace(" [aliases: ", " (aliases: ")
        .replace("`] —", "`) —")
        .replace("`] \n", "`) \n")
        .replace("`]\n", "`)\n")
}

