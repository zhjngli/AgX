fn split_field_path<'a>(base: &'a str, display_path: &'a str) -> Vec<&'a str> {
    let mut parts = vec![base];
    parts.extend(display_path.split('.'));
    parts
}

fn explanation_link_for_section(field_name: &str) -> Option<(&'static str, &'static str)> {
    match field_name {
        "grain" => Some(("grain", "Grain")),
        _ => None,
    }
}

fn format_f32_default(value: f32) -> String {
    format_number(f64::from(value))
}

fn format_display_default(value: impl std::fmt::Display) -> String {
    format!("`{value}`")
}

fn format_option_u64_default(value: Option<u64>) -> String {
    match value {
        Some(value) => value.to_string(),
        None => "null".to_owned(),
    }
}

fn format_points_default(points: &[(f32, f32)]) -> String {
    let pairs = points
        .iter()
        .map(|(x, y)| format!("({}, {})", format_f32_default(*x), format_f32_default(*y)))
        .collect::<Vec<_>>();
    format!("[{}]", pairs.join(", "))
}

