fn main() {
    if let Err(error) = generate_cli_reference().and_then(|_| generate_preset_reference()) {
        eprintln!("agx-docgen: {error}");
        std::process::exit(1);
    }
}

fn generate_cli_reference() -> io::Result<PathBuf> {
    let output_dir = repo_root().join(OUTPUT_DIR);
    fs::create_dir_all(&output_dir)?;

    let command = agx_cli::build_cli();
    let markdown = clap_markdown::help_markdown_command_custom(
        &command,
        &MarkdownOptions::new().show_footer(false),
    );
    let markdown = sanitize_markdown(&markdown);

    let output_path = output_dir.join(CLI_OUTPUT_FILE);
    let contents = format!("{GENERATED_HEADER}\n{CLI_PAGE_TITLE}\n\n{markdown}");
    fs::write(&output_path, contents)?;

    println!("generated {}", output_path.display());

    Ok(output_path)
}

fn generate_preset_reference() -> io::Result<PathBuf> {
    let output_dir = repo_root().join(OUTPUT_DIR);
    let output_path = output_dir.join(PRESET_OUTPUT_FILE);
    generate_preset_reference_to(&output_path)
}

fn generate_preset_reference_to(output_path: &Path) -> io::Result<PathBuf> {
    let output_dir = output_path
        .parent()
        .expect("preset output path should have a parent directory");
    fs::create_dir_all(output_dir)?;

    let schema = schemars::schema_for!(agx::Parameters);
    let contents = render_preset_reference(&schema);
    fs::write(output_path, contents)?;

    println!("generated {}", output_path.display());

    Ok(output_path.to_path_buf())
}

