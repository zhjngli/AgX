fn render_manual_section(
    title: &str,
    description: &str,
    rows: &[(&str, &str, &str, &str)],
) -> String {
    let mut section = format!("## {title}\n\n{description}\n\n{}", markdown_table_header());
    for &(field, range, default, note) in rows {
        section.push_str(&format_manual_row(field, range, default, note));
    }
    section.push('\n');
    section
}

fn render_prefixed_flat_section(
    schema: &RootSchema,
    section_name: &str,
    description: &str,
    fields: &[&str],
) -> String {
    let mut section = format!(
        "## {section_name}\n\n{description}\n\n{}",
        markdown_table_header()
    );
    for &field in fields {
        let display_name = format!("{section_name}.{field}");
        let schema_path = vec![field];
        section.push_str(&format_field_row(schema, &schema_path, &display_name));
    }
    section.push('\n');
    section
}

fn format_field_row(schema: &RootSchema, field_path: &[&str], field_name: &str) -> String {
    let field_schema = schema_at_path(schema, field_path);
    format!(
        "| `{}` | {} | {} | {} |\n",
        field_name,
        escape_table_cell(&get_range_string(schema, field_path, field_schema)),
        escape_table_cell(&get_default_string(field_path, field_schema)),
        escape_table_cell(&get_description(field_schema))
    )
}

fn format_manual_row(field_name: &str, range: &str, default: &str, note: &str) -> String {
    format!(
        "| `{}` | {} | {} | {} |\n",
        field_name,
        escape_table_cell(range),
        escape_table_cell(default),
        escape_table_cell(note)
    )
}

fn resolve_ref<'a>(root: &'a RootSchema, schema: &'a SchemaObject) -> &'a SchemaObject {
    let mut current = schema;
    'resolve: loop {
        if let Some(reference) = current.reference.as_deref() {
            current = definition_schema(root, reference);
            continue;
        }

        if let Some(subschemas) = current.subschemas.as_ref() {
            for variants in [&subschemas.all_of, &subschemas.any_of, &subschemas.one_of] {
                if let Some(items) = variants.as_deref() {
                    if items.len() == 1 {
                        current = schema_object(&items[0]);
                        continue 'resolve;
                    }
                }
            }
        }

        return current;
    }
}

fn get_range_string(
    schema: &RootSchema,
    field_path: &[&str],
    field_schema: &SchemaObject,
) -> String {
    let field_schema = resolve_ref(schema, field_schema);

    if let Some(range) = range_override(field_path) {
        return range.to_owned();
    }

    if let Some(enum_values) = field_schema.enum_values.as_ref() {
        if !enum_values.is_empty() {
            return enum_values
                .iter()
                .map(format_json_value)
                .collect::<Vec<_>>()
                .join(", ");
        }
    }

    if let Some(number) = field_schema.number.as_ref() {
        if let (Some(min), Some(max)) = (number.minimum, number.maximum) {
            return format!("{} to {}", format_number(min), format_number(max));
        }
    }

    if let Some(subschemas) = field_schema.subschemas.as_ref() {
        for variants in [&subschemas.any_of, &subschemas.one_of] {
            if let Some(items) = variants.as_deref() {
                let mut enum_values = Vec::new();
                let mut type_values = Vec::new();
                for item in items {
                    let object = resolve_ref(schema, schema_object(item));
                    if let Some(const_value) = object.const_value.as_ref() {
                        enum_values.push(format_json_value(const_value));
                        continue;
                    }
                    if let Some(values) = object.enum_values.as_ref() {
                        enum_values.extend(values.iter().map(format_json_value));
                        continue;
                    }
                    if let Some(type_name) = primitive_type_name(object) {
                        type_values.push(type_name);
                    }
                }
                if !enum_values.is_empty() {
                    enum_values.dedup();
                    return enum_values.join(", ");
                }
                if !type_values.is_empty() {
                    type_values.dedup();
                    return type_values.join(" or ");
                }
            }
        }
    }

    primitive_type_name(field_schema).unwrap_or_else(|| "—".to_owned())
}

fn get_default_string(field_path: &[&str], field_schema: &SchemaObject) -> String {
    if let Some(default) = field_schema
        .metadata
        .as_ref()
        .and_then(|metadata| metadata.default.as_ref())
    {
        return format_json_value(default);
    }

    canonical_default_string(field_path).unwrap_or_else(|| "—".to_owned())
}

fn get_description(field_schema: &SchemaObject) -> String {
    let Some(description) = field_schema
        .metadata
        .as_ref()
        .and_then(|metadata| metadata.description.as_deref())
    else {
        return "—".to_owned();
    };

    let description = description.trim().replace('\n', " ");
    let first_line = description.lines().next().unwrap_or(&description).trim();
    let first_sentence = first_line
        .split_terminator(". ")
        .next()
        .unwrap_or(first_line)
        .trim();

    if first_sentence.ends_with('.') {
        first_sentence.to_owned()
    } else {
        format!("{first_sentence}.")
    }
}

fn render_nested_section(
    schema: &RootSchema,
    title: &str,
    description: &str,
    field_name: &str,
) -> String {
    let mut section = format!("## {title}\n\n{description}\n\n{}", markdown_table_header());

    if let Some(paths) = preferred_nested_field_paths(field_name) {
        for &display_path in paths {
            let (schema_path, display_name) = if field_name == "grain" && display_path == "type" {
                (
                    split_field_path(field_name, "grain_type"),
                    format!("grain.{display_path}"),
                )
            } else {
                (
                    split_field_path(field_name, display_path),
                    format!("{field_name}.{display_path}"),
                )
            };
            section.push_str(&format_field_row(schema, &schema_path, &display_name));
        }
    } else {
        let mut rows = Vec::new();
        collect_leaf_paths(schema, &[field_name], field_name, &mut rows);
        for (path, display_name) in rows {
            let path_refs = path.iter().map(String::as_str).collect::<Vec<_>>();
            let display_name = format!("{field_name}.{display_name}");
            section.push_str(&format_field_row(schema, &path_refs, &display_name));
        }
    }

    section.push('\n');
    if let Some((slug, label)) = explanation_link_for_section(field_name) {
        add_explanation_links(&mut section, slug, label);
    }
    section
}

fn render_hsl_section(schema: &RootSchema) -> String {
    let mut section = format!(
        "## hsl\n\nAdjusts hue, saturation, and luminance for each HSL color channel.\n\n{}",
        markdown_table_header()
    );
    for &channel in HSL_CHANNELS {
        for &component in HSL_COMPONENTS {
            let display = format!("hsl.{channel}.{component}");
            section.push_str(&format_field_row(
                schema,
                &["hsl", channel, component],
                &display,
            ));
        }
    }
    section.push('\n');
    section
}

fn add_explanation_links(section: &mut String, explanation_slug: &str, label: &str) {
    let path = repo_root()
        .join("docs/book/src/explanation/algorithms")
        .join(format!("{explanation_slug}.md"));
    if path.exists() {
        section.push_str(&format!(
            "\nSee [{label}](../explanation/algorithms/{explanation_slug}.md) for details.\n"
        ));
    }
}

fn schema_at_path<'a>(root: &'a RootSchema, path: &[&str]) -> &'a SchemaObject {
    let mut current = &root.schema;
    for segment in path {
        current = property_schema(root, current, segment);
    }
    current
}

fn property_schema<'a>(
    root: &'a RootSchema,
    schema: &'a SchemaObject,
    property: &str,
) -> &'a SchemaObject {
    let resolved = resolve_ref(root, schema);
    let object = resolved
        .object
        .as_ref()
        .unwrap_or_else(|| panic!("schema at '{}' is not an object", property));
    let property_schema = object
        .properties
        .get(property)
        .unwrap_or_else(|| panic!("missing property '{property}'"));
    resolve_ref(root, schema_object(property_schema))
}

fn definition_schema<'a>(root: &'a RootSchema, reference: &str) -> &'a SchemaObject {
    let name = reference
        .strip_prefix("#/definitions/")
        .unwrap_or_else(|| panic!("unsupported schema reference: {reference}"));
    let schema = root
        .definitions
        .get(name)
        .unwrap_or_else(|| panic!("missing schema definition '{name}'"));
    resolve_ref(root, schema_object(schema))
}

fn schema_object(schema: &Schema) -> &SchemaObject {
    match schema {
        Schema::Bool(value) => panic!("unexpected bool schema: {value}"),
        Schema::Object(object) => object,
    }
}

fn collect_leaf_paths(
    root: &RootSchema,
    path: &[&str],
    display_name: &str,
    rows: &mut Vec<(Vec<String>, String)>,
) {
    let schema = schema_at_path(root, path);
    let schema = resolve_ref(root, schema);
    if let Some(object) = schema.object.as_ref() {
        if !object.properties.is_empty() {
            let property_names = object
                .properties
                .keys()
                .map(String::as_str)
                .collect::<Vec<_>>();
            for property in property_names {
                let mut next_path = path.to_vec();
                next_path.push(property);
                let next_display = if display_name.is_empty() {
                    property.to_owned()
                } else {
                    format!("{display_name}.{property}")
                };
                collect_leaf_paths(root, &next_path, &next_display, rows);
            }
            return;
        }
    }

    rows.push((
        path.iter().map(|segment| (*segment).to_owned()).collect(),
        display_name.to_owned(),
    ));
}

fn markdown_table_header() -> &'static str {
    "| Field | Range / Values | Default | Note |\n| --- | --- | --- | --- |\n"
}

fn escape_table_cell(value: &str) -> String {
    value
        .replace('|', "\\|")
        .replace('[', "&#91;")
        .replace(']', "&#93;")
        .replace('\n', " ")
}

fn format_json_value(value: &impl std::fmt::Display) -> String {
    let rendered = value.to_string();
    if rendered.starts_with('"') && rendered.ends_with('"') && rendered.len() >= 2 {
        return format!("`{}`", &rendered[1..rendered.len() - 1]);
    }
    if let Ok(number) = rendered.parse::<f64>() {
        return format_number(number);
    }
    rendered
}

fn format_number(value: f64) -> String {
    let mut formatted = value.to_string();
    if let Some(stripped) = formatted.strip_suffix(".0") {
        formatted = stripped.to_owned();
    }
    formatted
}

fn primitive_type_name(schema: &SchemaObject) -> Option<String> {
    match schema.instance_type.as_ref()? {
        SingleOrVec::Single(instance) => Some(instance_type_name(instance).to_owned()),
        SingleOrVec::Vec(instances) => {
            let names = instances.iter().map(instance_type_name).collect::<Vec<_>>();
            if names.is_empty() {
                None
            } else {
                Some(names.join(" or "))
            }
        }
    }
}

fn instance_type_name(instance: &InstanceType) -> &'static str {
    match instance {
        InstanceType::Null => "null",
        InstanceType::Boolean => "boolean",
        InstanceType::Object => "object",
        InstanceType::Array => "array",
        InstanceType::Number => "number",
        InstanceType::String => "string",
        InstanceType::Integer => "integer",
    }
}

