//! Generates CLI and preset reference pages for the AgX documentation site.
//!
//! Output is written to `docs/book/src/reference/` and consumed by mdbook.

use std::{fs, io, path::PathBuf};

use clap_markdown::MarkdownOptions;
use schemars::schema::{InstanceType, RootSchema, Schema, SchemaObject, SingleOrVec};

const OUTPUT_DIR: &str = "docs/book/src/reference";
const CLI_OUTPUT_FILE: &str = "cli.md";
const PRESET_OUTPUT_FILE: &str = "preset.md";
const GENERATED_HEADER: &str = "<!-- Generated by agx-docgen. Do not edit manually. -->";
const CLI_PAGE_TITLE: &str = "# CLI Reference";
const PRESET_PAGE_TITLE: &str = "# Preset Format Reference";
const CLAP_MARKDOWN_TITLE: &str = "# Command-Line Help for `agx`";
const PER_PIXEL_FIELDS: &[&str] = &[
    "exposure",
    "contrast",
    "highlights",
    "shadows",
    "whites",
    "blacks",
    "temperature",
    "tint",
];
const HSL_CHANNELS: &[&str] = &[
    "red", "orange", "yellow", "green", "aqua", "blue", "purple", "magenta",
];
const HSL_COMPONENTS: &[&str] = &["hue", "saturation", "luminance"];

fn main() {
    if let Err(error) = generate_cli_reference().and_then(|_| generate_preset_reference()) {
        eprintln!("agx-docgen: {error}");
        std::process::exit(1);
    }
}

fn generate_cli_reference() -> io::Result<PathBuf> {
    let output_dir = repo_root().join(OUTPUT_DIR);
    fs::create_dir_all(&output_dir)?;

    let command = agx_cli::build_cli();
    let markdown = clap_markdown::help_markdown_command_custom(
        &command,
        &MarkdownOptions::new().show_footer(false),
    );
    let markdown = sanitize_markdown(&markdown);

    let output_path = output_dir.join(CLI_OUTPUT_FILE);
    let contents = format!("{GENERATED_HEADER}\n{CLI_PAGE_TITLE}\n\n{markdown}");
    fs::write(&output_path, contents)?;

    println!("generated {}", output_path.display());

    Ok(output_path)
}

fn generate_preset_reference() -> io::Result<PathBuf> {
    let output_dir = repo_root().join(OUTPUT_DIR);
    fs::create_dir_all(&output_dir)?;

    let schema = schemars::schema_for!(agx::Parameters);
    let contents = render_preset_reference(&schema);

    let output_path = output_dir.join(PRESET_OUTPUT_FILE);
    fs::write(&output_path, contents)?;

    println!("generated {}", output_path.display());

    Ok(output_path)
}

